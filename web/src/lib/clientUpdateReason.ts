/** 将更新诊断映射为可翻译的用户处理提示。 */
export function clientUpdateReasonKey(message: string): string {
  if (message.includes('未保存')) return 'unsaved'
  if (message.includes('任务尚未完成') || message.includes('未收尾打印')) return 'jobs'
  if (message.includes('回报')) return 'results'
  if (message.includes('界面仍在使用')) return 'active'
  if (message.includes('维护时间')) return 'window'
  if (message.includes('部分界面未确认') || message.includes('界面会话过多')) return 'ui'
  if (message.includes('不支持受控更新')) return 'server'
  if (message.includes('配置并连接')) return 'disconnected'
  if (message.includes('当前没有适用')) return 'noRelease'
  if (message.includes('发布已暂停或更新')) return 'eligibility'
  if (message.includes('系统提示稍后需重启')) return 'reboot'
  if (message.includes('更新及恢复检查通过')) return 'completed'
  if (message.includes('旧版已完整恢复')) return 'restored'
  if (message.includes('更新恢复') || message.includes('记录损坏')) return 'repair'
  if (message.includes('插件')) return 'plugins'
  if (message.includes('安装服务') || message.includes('更新服务') || message.includes('更新路径') || message.includes('Program Files')) return 'bootstrap'
  if (message.includes('正在处理操作') || message.includes('正在停止或维护')) return 'busy'
  if (message.includes('检查或下载失败')) return 'offline'
  if (message.includes('草稿安装包不存在')) return 'draft'
  if (['证书', '签名', '发布者', '摘要', '不兼容', '文件名', '元数据', '不是 LabelFrame', '不能覆盖', '已发布', '大小'].some(word => message.includes(word))) return 'package'
  return 'failed'
}
