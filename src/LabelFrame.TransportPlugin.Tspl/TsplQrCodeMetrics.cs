        { 134, 106, 74, 58 },
        { 154, 122, 86, 64 },
        { 192, 152, 108, 84 },
        { 230, 180, 130, 98 },
        { 271, 213, 151, 119 }, // V10
        { 321, 251, 177, 137 },
        { 367, 287, 203, 155 },
        { 425, 331, 241, 177 },
        { 458, 362, 258, 194 },
        { 520, 412, 292, 220 },
        { 586, 450, 322, 250 },
        { 644, 504, 364, 280 },
        { 718, 560, 394, 310 },
        { 792, 624, 442, 338 },
        { 858, 666, 482, 382 }, // V20
        { 929, 711, 509, 403 },
        { 1003, 779, 565, 439 },
        { 1091, 857, 611, 461 },
        { 1171, 911, 661, 511 },
        { 1273, 997, 715, 535 },
