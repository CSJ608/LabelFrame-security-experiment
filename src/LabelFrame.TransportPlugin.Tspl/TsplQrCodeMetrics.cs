        { 2699, 2099, 1499, 1139 },
        { 2809, 2213, 1579, 1219 },
        { 2953, 2331, 1663, 1273 }, // V40
    };

    /// <summary>
    /// 按数据 UTF-8 字节数与纠错级别估算最小可容版本（1..40）；
    /// 超出 V40 容量的极端长值封顶 V40（打印机自行处理，编译不因此失败）。
    /// </summary>
    internal static int EstimateVersion(int utf8ByteCount, LabelQrEcc ecc)
    {
        var eccIndex = (int)ecc;
        for (var version = 1; version <= 40; version++)
        {
            if (ByteModeCapacities[version - 1, eccIndex] >= utf8ByteCount)
            {
                return version;
            }
        }

        return 40;
    }

    /// <summary>版本 → 矩阵边长模块数（V1=21、每级 +4，即 17 + 4v）。</summary>
    internal static int MatrixModules(int version)
        => 17 + 4 * version;
}
