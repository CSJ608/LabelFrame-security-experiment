using LabelFrame.Core.Layout;

namespace LabelFrame.TransportPlugin.Tspl;

/// <summary>
/// QR 码符号度量：字节模式数据容量表（ISO/IEC 18004）+ 版本 → 模块数换算，仅供编译期估算 QRCODE
/// cell width（估算按字节模式取最小可容版本；打印机自动模式可能选更紧凑模式致实际略小，属尽力近似不作阻断）。
/// 与 Zebra 插件的同构知识各自独立成表（插件间零共享依赖——只依赖 Core）。
/// </summary>
internal static class TsplQrCodeMetrics
{
    /// <summary>
    /// 字节模式数据容量（字节）——按版本 1..40 × ECC（L / M / Q / H，与 <see cref="LabelQrEcc"/> 枚举序一致）；
    /// ISO/IEC 18004 标准容量表。
    /// </summary>
    internal static readonly int[,] ByteModeCapacities =
    {
        // L M Q H
        { 17, 14, 11, 7 }, // V1
        { 32, 26, 20, 14 },
        { 53, 42, 32, 24 },
